def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--expand", action="store_true")
    args = parser.parse_args()

    # Load existing progress
    prog = {"downloaded": [], "indexed": [], "failed": []}
    if PROGRESS_FILE.exists():
        prog = json.loads(PROGRESS_FILE.read_text())

    current_ids = set(prog.get("downloaded", []) + prog.get("indexed", []))
    logger.info(f"Current catalog: {len(current_ids)} IMDb IDs")
    logger.info(f"Extended catalog: {len(EXTENDED_MOVIES)} IMDb IDs")

    new_ids = set(EXTENDED_MOVIES.keys()) - current_ids
    logger.info(f"New IDs to add: {len(new_ids)}")
    logger.info(f"After expansion: {len(current_ids) + len(new_ids)} total")

    if args.check:
        return

    if args.expand:
        # Add all new IDs to downloaded list
        all_ids = sorted(current_ids | set(EXTENDED_MOVIES.keys()))
        prog["downloaded"] = all_ids
        prog["indexed"] = []
        prog["failed"] = []

        with open(PROGRESS_FILE, "w") as f:
            json.dump(prog, f, indent=2)
        logger.info(f"Updated trailer_progress.json: {len(all_ids)} total IDs")

        # Save title cache
        titles = {}
        if TITLES_FILE.exists():
            titles = json.loads(TITLES_FILE.read_text())
        titles.update(EXTENDED_MOVIES)
        with open(TITLES_FILE, "w") as f:
            json.dump(titles, f, indent=2, ensure_ascii=False)
        logger.info(f"Saved imdb_titles_cache.json: {len(titles)} titles")


if __name__ == "__main__":
    main()
